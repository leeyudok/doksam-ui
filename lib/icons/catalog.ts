export function searchIcons(query: string, category?: IconCategory): CatalogIcon[] {
  const q = query.trim().toLowerCase();
  return ICON_CATALOG.filter((icon) => {
    if (category && icon.category !== category) return false;
    if (!q) return true;
    return (
      icon.name.toLowerCase().includes(q) ||
      icon.keywords.some((keyword) => keyword.toLowerCase().includes(q))
    );
  });
}
