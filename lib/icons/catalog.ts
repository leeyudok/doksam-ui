export interface CatalogIcon {
  /** 공식 컴포넌트명 (예: "HouseIcon"). import 문에 그대로 쓴다. */
  name: string;
  Icon: Icon;
  /** 영문+한글 검색어. */
  keywords: string[];
  category: IconCategory;
}

/** [name, Icon, keywords] 튜플로 카테고리별 정의를 압축한다. */
type Entry = [string, Icon, string[]];

function define(category: IconCategory, entries: Entry[]): CatalogIcon[] {
  return entries.map(([name, IconComponent, keywords]) => ({
    name,
    Icon: IconComponent,
    keywords,
    category,
  }));
}

