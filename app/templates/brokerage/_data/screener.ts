  changePercent: number
  changeAmount: number
  /** 거래대금(원) */
  tradingValue: number
  /** 거래량(주) */
  volume: number
  /** 시가총액(원) */
  marketCap: number
  /** 매수 비율(0~100) — 매도 비율은 100 - buyRatio */
